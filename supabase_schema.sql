-- Supabase Schema for St Vincent's Gastro Department Management

-- 1. Staff table
CREATE TABLE IF NOT EXISTS staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE,
    role TEXT DEFAULT 'consultant', -- consultant, registrar, fellow, coordinator
    is_coordinator INTEGER DEFAULT 0,
    pin TEXT DEFAULT '1234'
);

-- 2. Roster entries
CREATE TABLE IF NOT EXISTS roster_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_type TEXT NOT NULL, -- 'hm_oncall', 'ibd_wards', 'liver_wards', 'consults', 'gicc', 'friday_jc', 'ibd_meeting'
    date TEXT NOT NULL,       -- YYYY-MM-DD
    day_of_week TEXT,
    title TEXT,
    staff_name TEXT NOT NULL,
    role_label TEXT,
    notes TEXT,
    holiday TEXT,
    original_staff_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Swap requests
CREATE TABLE IF NOT EXISTS swap_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_staff_name TEXT NOT NULL,
    requester_entry_id BIGINT REFERENCES roster_entries(id) ON DELETE CASCADE,
    peer_staff_name TEXT NOT NULL,
    peer_entry_id BIGINT REFERENCES roster_entries(id) ON DELETE SET NULL,
    status TEXT DEFAULT 'pending_peer', -- 'pending_peer', 'pending_coordinator', 'approved', 'rejected'
    reason TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    peer_responded_at TIMESTAMPTZ,
    coordinator_responded_at TIMESTAMPTZ
);

-- 4. Leave applications
CREATE TABLE IF NOT EXISTS leave_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_name TEXT NOT NULL,
    employee_number TEXT,
    department TEXT DEFAULT 'Gastroenterology',
    pay_in_advance TEXT DEFAULT 'No',
    leave_type TEXT NOT NULL,
    start_date TEXT NOT NULL,
    end_date TEXT NOT NULL,
    leave_hours TEXT,
    leave_balance TEXT,
    costing TEXT,
    allowances TEXT,
    submission_date TEXT,
    status TEXT DEFAULT 'submitted', -- 'submitted', 'approved', 'rejected'
    manager_name TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable public access for demo / anon key (hospital internal micro-tool)
ALTER TABLE staff ENABLE ROW LEVEL SECURITY;
ALTER TABLE roster_entries ENABLE ROW LEVEL SECURITY;
ALTER TABLE swap_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE leave_applications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read/write staff" ON staff FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public read/write roster" ON roster_entries FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public read/write swaps" ON swap_requests FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Public read/write leave" ON leave_applications FOR ALL USING (true) WITH CHECK (true);
